<?php

declare(strict_types=1);

namespace Thesis\Amqp;

use Testo\Assert;
use Testo\Test;
use function Thesis\Amqp\Codegen\generate;

#[Test]
final class CodegenTest
{
    public function generatedFilesAreUpToDate(): void
    {
        $package = \dirname(__DIR__);

        $generated = generate("{$package}/codegen/amqp0-9-1.extended.xml");

        foreach ($generated as $path => $contents) {
            Assert::same(
                actual: file_get_contents("{$package}/{$path}"),
                expected: $contents,
                message: "{$path} is outdated: run `php packages/amqp/codegen/generate.php`.",
            );
        }

        $marker = '// Generated by codegen/generate.php';

        $files = glob("{$package}/src/Internal/Protocol/*.php");

        foreach ($files === false ? [] : $files as $file) {
            $path = substr($file, \strlen($package) + 1);

            if (str_contains((string) file_get_contents($file), $marker)) {
                Assert::true(isset($generated[$path]), "{$path} is no longer generated: delete it.");
            }
        }
    }
}
