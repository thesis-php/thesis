<?php

declare(strict_types=1);

namespace Thesis\Amqp\Codegen;

/**
 * Generates the protocol layer of thesis/amqp from amqp0-9-1.extended.xml of RabbitMQ.
 *
 * Run it as a script to write the files: `php packages/amqp/codegen/generate.php`.
 * Required, it only declares generate(), which a test compares with the files in src/.
 */
const HEADER = '// Generated by codegen/generate.php from codegen/amqp0-9-1.extended.xml, do not edit.';

const PHP_TYPES = [
    'bit' => 'bool',
    'octet' => 'int',
    'short' => 'int',
    'long' => 'int',
    'longlong' => 'int',
    'shortstr' => 'string',
    'longstr' => 'string',
    'timestamp' => 'int',
    'table' => 'array',
];

const PHPDOC_TYPES = [
    'octet' => 'int<0, 255>',
    'short' => 'int<0, 65535>',
    'long' => 'int<0, 4294967295>',
    'longlong' => 'non-negative-int',
    'timestamp' => 'non-negative-int',
    'table' => 'array<string, mixed>',
];

const READ = [
    'octet' => '$buffer->readUint8()',
    'short' => '$buffer->readUint16()',
    'long' => '$buffer->readUint32()',
    'longlong' => '$buffer->readUint64()',
    'timestamp' => '$buffer->readUint64()',
    'shortstr' => 'Fields::readShortString($buffer)',
    'longstr' => 'Fields::readLongString($buffer)',
    'table' => 'Fields::readTable($buffer)',
];

const WRITE = [
    'octet' => '$buffer->writeUint8(%s);',
    'short' => '$buffer->writeUint16(%s);',
    'long' => '$buffer->writeUint32(%s);',
    'longlong' => '$buffer->writeUint64(%s);',
    'timestamp' => '$buffer->writeUint64(%s);',
    'shortstr' => 'Fields::writeShortString($buffer, %s);',
    'longstr' => 'Fields::writeLongString($buffer, %s);',
    'table' => 'Fields::writeTable($buffer, %s);',
];

const RESERVED_VALUES = [
    'octet' => '0',
    'short' => '0',
    'long' => '0',
    'longlong' => '0',
    'shortstr' => "''",
    'longstr' => "''",
    'table' => '[]',
];

const SKIP = [
    'octet' => '$buffer->skip(1);',
    'short' => '$buffer->skip(2);',
    'long' => '$buffer->skip(4);',
    'longlong' => '$buffer->skip(8);',
    'shortstr' => 'Fields::readShortString($buffer);',
    'longstr' => 'Fields::readLongString($buffer);',
    'table' => 'Fields::readTable($buffer);',
];

/**
 * @return array<non-empty-string, string> contents by the path relative to the package
 */
function generate(string $specFile): array
{
    $spec = simplexml_load_file($specFile);

    if ($spec === false) {
        throw new \RuntimeException("Failed to parse {$specFile}.");
    }

    $domains = [];

    foreach (children($spec, 'domain') as $domain) {
        $domains[attribute($domain, 'name')] = attribute($domain, 'type');
    }

    $files = [];
    $decoders = [];

    foreach (children($spec, 'class') as $class) {
        $className = attribute($class, 'name');
        $classId = (int) attribute($class, 'index');
        $methods = [];

        foreach (children($class, 'method') as $method) {
            $methodName = attribute($method, 'name');
            $methodId = (int) attribute($method, 'index');
            $name = pascalCase($className) . pascalCase($methodName);
            $files["src/Internal/Protocol/{$name}.php"] = methodClass(
                name: $name,
                label: "{$className}.{$methodName}: " . attribute($method, 'label') . '.',
                classId: $classId,
                methodId: $methodId,
                fields: fields($method, $domains),
            );
            $methods[$methodId] = $name;
        }

        $decoders[$classId] = $methods;

        if ($className === 'basic') {
            $files['src/Internal/Protocol/BasicProperties.php'] = propertiesClass(fields($class, $domains));
        }
    }

    $files['src/Internal/Protocol/Methods.php'] = methodsClass($decoders);
    $files['src/ReplyCode.php'] = replyCode($spec);

    ksort($files);

    return $files;
}

/**
 * @param array<string, string> $domains
 * @return list<array{name: string, type: string, reserved: bool}>
 */
function fields(\SimpleXMLElement $element, array $domains): array
{
    $fields = [];

    foreach (children($element, 'field') as $field) {
        $name = attribute($field, 'name');
        $type = attribute($field, 'type');
        $fields[] = [
            'name' => camelCase($name),
            'type' => $type === '' ? lookup($domains, attribute($field, 'domain')) : $type,
            'reserved' => attribute($field, 'reserved') !== '' || $name === 'reserved',
        ];
    }

    return $fields;
}

/**
 * @param list<array{name: string, type: string, reserved: bool}> $fields
 */
function methodClass(string $name, string $label, int $classId, int $methodId, array $fields): string
{
    $parameters = array_values(array_filter($fields, static fn(array $field) => !$field['reserved']));

    $phpdoc = [];
    $promoted = [];

    foreach ($parameters as $field) {
        if (isset(PHPDOC_TYPES[$field['type']])) {
            $phpdoc[] = '     * @param ' . lookup(PHPDOC_TYPES, $field['type']) . " \${$field['name']}";
        }

        $promoted[] = '        public ' . lookup(PHP_TYPES, $field['type']) . " \${$field['name']},";
    }

    $constructor = '';

    if ($promoted !== []) {
        $constructor = "\n\n";

        if ($phpdoc !== []) {
            $constructor .= "    /**\n" . implode("\n", $phpdoc) . "\n     */\n";
        }

        $constructor .= "    public function __construct(\n" . implode("\n", $promoted) . "\n    ) {}";
    }

    [$decode, $arguments] = decodeFields($fields);
    $decodeBody = $decode === [] ? '' : implode("\n", $decode) . "\n\n";

    if ($arguments === []) {
        $decodeBody .= '        return new self();';
    } elseif (\count($arguments) === 1) {
        $decodeBody .= '        return new self(' . trim($arguments[0], ' ,') . ');';
    } else {
        $decodeBody .= "        return new self(\n" . implode("\n", $arguments) . "\n        );";
    }

    $encode = ['        $buffer->writeUint16(self::CLASS_ID)->writeUint16(self::METHOD_ID);'];

    foreach (encodeFields($fields, '$this->') as $line) {
        $encode[] = $line;
    }

    $decodeMethod = "    public static function decode(Buffer \$buffer): self\n    {\n{$decodeBody}\n    }";
    $encode = implode("\n", $encode);
    $header = HEADER;

    return <<<PHP
        <?php

        declare(strict_types=1);

        {$header}

        namespace Thesis\\Amqp\\Internal\\Protocol;

        use Thesis\\Io\\Buffer;

        /**
         * {$label}
         *
         * @internal
         */
        final readonly class {$name} implements Method
        {
            public const int CLASS_ID = {$classId};
            public const int METHOD_ID = {$methodId};{$constructor}

        {$decodeMethod}

            public function encode(Buffer \$buffer): void
            {
        {$encode}
            }
        }

        PHP;
}

/**
 * @param list<array{name: string, type: string, reserved: bool}> $fields
 * @return array{list<string>, list<string>} the statements that read the fields and the arguments of the constructor
 */
function decodeFields(array $fields): array
{
    $statements = [];
    $arguments = [];

    foreach (groupBits($fields) as $group) {
        if (isBitGroup($group)) {
            $hasValues = array_filter($group, static fn(array $bit) => !$bit['reserved']) !== [];

            if (!$hasValues) {
                $statements[] = '        $buffer->skip(1);';

                continue;
            }

            $variable = \count($group) === 1 ? '$bit' : '$bits';
            $statements[] = "        {$variable} = \$buffer->readUint8();";

            foreach ($group as $index => $bit) {
                if (!$bit['reserved']) {
                    $arguments[] = "            {$bit['name']}: ({$variable} & " . bitMask($index) . ') !== 0,';
                }
            }

            continue;
        }

        foreach ($group as $field) {
            if ($field['reserved']) {
                $statements[] = '        ' . lookup(SKIP, $field['type']);

                continue;
            }

            $statements[] = "        \${$field['name']} = " . lookup(READ, $field['type']) . ';';
            $arguments[] = "            {$field['name']}: \${$field['name']},";
        }
    }

    return [$statements, $arguments];
}

/**
 * @param list<array{name: string, type: string, reserved: bool}> $fields
 * @return list<string>
 */
function encodeFields(array $fields, string $prefix): array
{
    $statements = [];

    foreach (groupBits($fields) as $group) {
        if (isBitGroup($group)) {
            $parts = [];

            foreach ($group as $index => $bit) {
                if (!$bit['reserved']) {
                    $parts[] = "{$prefix}{$bit['name']} ? " . bitMask($index) . ' : 0';
                }
            }

            $value = match (\count($parts)) {
                0 => '0',
                1 => $parts[0],
                default => "\n            (" . implode(")\n            | (", $parts) . "),\n        ",
            };
            $statements[] = "        \$buffer->writeUint8({$value});";

            continue;
        }

        foreach ($group as $field) {
            $value = $field['reserved'] ? lookup(RESERVED_VALUES, $field['type']) : "{$prefix}{$field['name']}";
            $statements[] = '        ' . \sprintf(lookup(WRITE, $field['type']), $value);
        }
    }

    return $statements;
}

/**
 * Consecutive bits share an octet, up to 8 of them.
 *
 * @param list<array{name: string, type: string, reserved: bool}> $fields
 * @return list<list<array{name: string, type: string, reserved: bool}>>
 */
function groupBits(array $fields): array
{
    $groups = [];
    $bits = [];

    foreach ($fields as $field) {
        if ($field['type'] === 'bit') {
            $bits[] = $field;

            if (\count($bits) === 8) {
                $groups[] = $bits;
                $bits = [];
            }

            continue;
        }

        if ($bits !== []) {
            $groups[] = $bits;
            $bits = [];
        }

        $groups[] = [$field];
    }

    if ($bits !== []) {
        $groups[] = $bits;
    }

    return $groups;
}

/**
 * @param list<array{name: string, type: string, reserved: bool}> $group
 */
function isBitGroup(array $group): bool
{
    return $group !== [] && $group[0]['type'] === 'bit';
}

function bitMask(int $index): string
{
    return '0b' . str_pad(decbin(1 << $index), 8, '0', STR_PAD_LEFT);
}

/**
 * @param list<array{name: string, type: string, reserved: bool}> $fields
 */
function propertiesClass(array $fields): string
{
    $phpdoc = [];
    $promoted = [];
    $decode = [];
    $arguments = [];
    $flags = [];
    $encode = [];

    foreach ($fields as $index => $field) {
        $flag = \sprintf('0x%04X', 1 << (15 - $index));

        if ($field['reserved']) {
            $skip = lookup(SKIP, $field['type']);
            $decode[] = "        if ((\$flags & {$flag}) !== 0) {\n            {$skip}\n        }";

            continue;
        }

        $name = $field['name'];

        if (isset(PHPDOC_TYPES[$field['type']])) {
            $phpdoc[] = '     * @param ?' . lookup(PHPDOC_TYPES, $field['type']) . " \${$name}";
        }

        $promoted[] = '        public ?' . lookup(PHP_TYPES, $field['type']) . " \${$name} = null,";
        $decode[] = "        \${$name} = (\$flags & {$flag}) !== 0 ? " . lookup(READ, $field['type']) . ' : null;';
        $arguments[] = "            {$name}: \${$name},";
        $flags[] = "            | (\$this->{$name} === null ? 0 : {$flag})";
        $encode[] = "        if (\$this->{$name} !== null) {\n            "
            . \sprintf(lookup(WRITE, $field['type']), "\$this->{$name}") . "\n        }";
    }

    $flagsExpression = ltrim(implode("\n", $flags), ' |');

    return implode("\n", [
        '<?php',
        '',
        'declare(strict_types=1);',
        '',
        HEADER,
        '',
        'namespace Thesis\Amqp\Internal\Protocol;',
        '',
        'use Thesis\Io\Buffer;',
        '',
        '/**',
        ' * The properties of a content header of the basic class, null if absent.',
        ' *',
        ' * @internal',
        ' */',
        'final readonly class BasicProperties',
        '{',
        '    /**',
        ...$phpdoc,
        '     */',
        '    public function __construct(',
        ...$promoted,
        '    ) {}',
        '',
        '    public static function decode(Buffer $buffer): self',
        '    {',
        '        $flags = $buffer->readUint16();',
        ...$decode,
        '',
        '        return new self(',
        ...$arguments,
        '        );',
        '    }',
        '',
        '    public function encode(Buffer $buffer): void',
        '    {',
        "        \$buffer->writeUint16(\n            {$flagsExpression},\n        );",
        ...$encode,
        '    }',
        '}',
        '',
    ]);
}

/**
 * @param array<int, array<int, string>> $decoders method classes by class id and method id
 */
function methodsClass(array $decoders): string
{
    $arms = [];

    foreach ($decoders as $classId => $methods) {
        $arms[] = "            {$classId} => match (\$methodId) {";

        foreach ($methods as $methodId => $class) {
            $arms[] = "                {$methodId} => {$class}::decode(\$buffer),";
        }

        $arms[] = '                default => throw ProtocolError::unknownMethod($classId, $methodId),';
        $arms[] = '            },';
    }

    $arms = implode("\n", $arms);
    $header = HEADER;

    return <<<PHP
        <?php

        declare(strict_types=1);

        {$header}

        namespace Thesis\\Amqp\\Internal\\Protocol;

        use Thesis\\Io\\Buffer;

        /**
         * @internal
         */
        final class Methods
        {
            /**
             * Decodes the payload of a method frame: the class id, the method id and the fields.
             *
             * @throws ProtocolError
             */
            public static function decode(Buffer \$buffer): Method
            {
                \$classId = \$buffer->readUint16();
                \$methodId = \$buffer->readUint16();

                return match (\$classId) {
        {$arms}
                    default => throw ProtocolError::unknownMethod(\$classId, \$methodId),
                };
            }
        }

        PHP;
}

function replyCode(\SimpleXMLElement $spec): string
{
    $cases = [];
    $hardErrors = [];

    foreach (children($spec, 'constant') as $constant) {
        $name = attribute($constant, 'name');
        $errorClass = attribute($constant, 'class');

        if (!str_starts_with($name, 'reply-') && $errorClass === '') {
            continue;
        }

        $case = pascalCase($name);
        $docs = children($constant, 'doc');
        $doc = trim((string) preg_replace('/\s+/', ' ', $docs === [] ? '' : (string) $docs[0]));
        $cases[] = '    /**';

        foreach (explode("\n", wordwrap($doc, 112)) as $line) {
            $cases[] = "     * {$line}";
        }

        $cases[] = '     */';
        $cases[] = "    case {$case} = " . attribute($constant, 'value') . ';';
        $cases[] = '';

        if ($errorClass === 'hard-error') {
            $hardErrors[] = "self::{$case}";
        }
    }

    $cases = rtrim(implode("\n", $cases));
    $hardErrors = implode(",\n", array_map(static fn(string $case) => "            {$case}", $hardErrors));
    $header = HEADER;

    return <<<PHP
        <?php

        declare(strict_types=1);

        {$header}

        namespace Thesis\\Amqp;

        /**
         * The reply code of connection.close and channel.close, of a returned message.
         *
         * @api
         */
        enum ReplyCode: int
        {
        {$cases}

            /**
             * A hard error closes the connection, a soft error only the channel.
             */
            public function isHardError(): bool
            {
                return match (\$this) {
        {$hardErrors} => true,
                    default => false,
                };
            }
        }

        PHP;
}

/**
 * @return list<\SimpleXMLElement>
 */
function children(\SimpleXMLElement $element, string $name): array
{
    $children = [];

    foreach ($element->children() ?? [] as $child) {
        if ($child->getName() === $name) {
            $children[] = $child;
        }
    }

    return $children;
}

function attribute(\SimpleXMLElement $element, string $name): string
{
    foreach ($element->attributes() ?? [] as $attribute) {
        if ($attribute->getName() === $name) {
            return (string) $attribute;
        }
    }

    return '';
}

/**
 * @param array<string, string> $map
 */
function lookup(array $map, string $key): string
{
    return $map[$key] ?? throw new \LogicException("Unknown \"{$key}\".");
}

function pascalCase(string $name): string
{
    return str_replace(' ', '', ucwords(str_replace('-', ' ', $name)));
}

function camelCase(string $name): string
{
    return lcfirst(pascalCase($name));
}

if (realpath(get_included_files()[0] ?? '') === __FILE__) {
    $package = \dirname(__DIR__);
    $generated = generate(__DIR__ . '/amqp0-9-1.extended.xml');

    $files = glob("{$package}/src/Internal/Protocol/*.php");

    foreach ($files === false ? [] : $files as $file) {
        $contents = file_get_contents($file);

        if ($contents !== false && str_contains($contents, HEADER)) {
            unlink($file);
        }
    }

    foreach ($generated as $path => $contents) {
        file_put_contents("{$package}/{$path}", $contents);
    }

    echo \sprintf("Generated %d files.\n", \count($generated));
}
