<?php

declare(strict_types=1);

namespace Thesis\Monorepo;

use Testo\Common\PluginConfigurator;

/**
 * packages/<dir>/package.php returns an instance of this class. The package's composer.json is generated from it.
 *
 * @api
 */
final readonly class Manifest
{
    /**
     * @param non-empty-string $description one sentence, it also goes to the package catalog in AGENTS.md
     * @param positive-int $licenseSince the first year of the copyright in LICENSE
     * @param non-empty-string $version the current series of the package, X.Y: '0.1', '2.0'. Changed by hand
     *     in the commit that starts a series: a break below 1.0, a new minor above (agents/versions.md)
     * @param ?non-empty-string $title the title of README.md, generated by sync. Defaults to Thesis and the words
     *     of the directory: 'Thesis Async Trace'. Set where a word is an acronym or a name: 'Thesis AMQP'
     * @param list<non-empty-string> $keywords composer keywords, also the topics of the split repository on GitHub,
     *     so each is a topic: lowercase letters, digits and hyphens, at most 50 characters, at most 20 of them
     * @param array<non-empty-string, non-empty-string> $require packages and platform requirements (php-64bit, ext-*).
     *     A monorepo package is required as 'thesis/<dir>' => '*', the range of its series is written instead
     *     (^0.Y below 1.0, ^X.0 above). A constraint within that range raises the lower bound: '^0.1.5'.
     *     php defaults to the constraint of monorepo.php
     * @param array<non-empty-string, non-empty-string> $requireDev package and platform requirements for tests.
     *     Use the same constraint format as $require.
     * @param bool $rootEntry the entry point of the package is named after it and lives in the root namespace:
     *     the class Thesis\<PascalCaseDir> in src/<PascalCaseDir>.php or the function Thesis\<camelCaseDir>()
     *     in src/api.php. The psr-4 prefix of src/ and tests/ is then Thesis\, the rest of them is
     *     in src/<PascalCaseDir>/ and tests/<PascalCaseDir>/, the test of the entry is tests/<PascalCaseDir>Test.php
     * @param list<non-empty-string> $files autoload files outside src/, relative to the package. The PHP files
     *     of src/ without a class, an interface, a trait or an enum are autoloaded without being listed
     * @param list<non-empty-string> $devFiles autoload-dev files outside tests/, relative to the package.
     *     The PHP files in tests/ without a class, interface, trait or enum are autoloaded without being listed.
     * @param array<non-empty-string, non-empty-string> $suggest
     * @param array<non-empty-string, non-empty-string> $conflict
     * @param list<non-empty-string> $optional packages and extensions of requireDev that src/ uses only when
     *     they are installed, behind a check: composer-dependency-analyser allows them in src/.
     *     Tell the users about them in $suggest
     * @param list<FixerSkip|RectorSkip> $skip files where a rule of a tool does not apply. PHPStan and Infection
     *     are not here: they are told in the code, by a phpstan-ignore or an infection-ignore comment with a reason
     * @param list<PluginConfigurator> $testoPlugins These plugins apply to the package's Testo suite.
     *     testo.php adds plugins that apply to every suite.
     * @param list<non-empty-string> $dist top-level entries of the package that src/ needs at runtime (a polyfill,
     *     resources). The split repository has only them, src/, composer.json, LICENSE, README.md,
     *     CHANGELOG.md, CONTRIBUTING.md, SECURITY.md and skills/
     * @param non-empty-string $type composer type: 'phpstan-extension' for a package that a composer plugin
     *     installs by its type
     * @param array<non-empty-string, mixed> $extra composer extra, the config of such a plugin. A file it names
     *     outside src/ goes to $dist too
     * @param bool $mutationTesting the job infect of check.yaml runs make infect on the tests/ of the package.
     *     Turned off with a comment on why
     * @param bool $bit32Testing CI tests the package on 32-bit PHP, which the package then guarantees.
     *     The tests run on the package's minimum PHP version and on the monorepo's PHP version (agents/platform.md).
     */
    public function __construct(
        public string $description,
        public int $licenseSince,
        public string $version,
        public ?string $title = null,
        public array $keywords = [],
        public array $require = [],
        public array $requireDev = [],
        public bool $rootEntry = false,
        public array $files = [],
        public array $devFiles = [],
        public array $suggest = [],
        public array $conflict = [],
        public array $optional = [],
        public array $skip = [],
        public array $testoPlugins = [],
        public array $dist = [],
        public string $type = 'library',
        public array $extra = [],
        public bool $mutationTesting = true,
        public bool $bit32Testing = false,
    ) {}
}
