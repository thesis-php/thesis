    private function packageOptions(): string
    {
        $options = array_map(
            static fn(Package $package) => '        - ' . $package->name,
            $this->monorepo->packages,
        );

        return implode("\n", $options);
    }

    /**
     * The badge says the level that CI checks, so it is read from the config and not repeated in the generator.
     *
     * @return non-empty-string
     */
    private function phpstanLevel(): string
    {
        $config = $this->monorepo->read('phpstan.neon') ?? '';

        if (preg_match('/^\s+level: (\w+)$/m', $config, $match) !== 1) {
            throw new MonorepoException('phpstan.neon must set parameters.level.');
        }

        return $match[1];
    }

    /**
     * A README without the markers yet loses its hand-written title: the generated one replaces it.
     */
    private static function withHead(string $readme, string $head): string
    {
        $start = strpos($readme, self::HEAD_START);
        $end = strpos($readme, self::HEAD_END);

        if ($start !== false && $end !== false && $start < $end) {
            $before = rtrim(substr($readme, 0, $start));
            $after = ltrim(substr($readme, $end + \strlen(self::HEAD_END)));
            $readme = $before . "\n\n" . $after;
        } elseif (str_starts_with(ltrim($readme), '# ')) {
            $afterTitle = strstr(ltrim($readme), "\n");
            $readme = $afterTitle === false ? '' : $afterTitle;
        }

        return self::HEAD_START . "\n\n" . $head . "\n\n" . self::HEAD_END . "\n\n" . ltrim($readme);
    }

    private static function isOutsideOfPackage(string $link): bool
    {
        $isUrl = preg_match('~^([a-z][a-z0-9+.-]*:|//)~i', $link) === 1;

        if ($isUrl || str_starts_with($link, '#')) {
            return false;
        }

        if (str_starts_with($link, '/')) {
            return true;
        }

        $path = substr($link, 0, strcspn($link, '?#'));
        $depth = 0;

        foreach (explode('/', $path) as $segment) {
            $depth += match ($segment) {
                '..' => -1,
                '', '.' => 0,
                default => 1,
            };

            if ($depth < 0) {
                return true;
            }
        }

        return false;
    }

