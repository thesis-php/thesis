    }

    private function skills(): string
    {
        $current = $this->monorepo->read('skills.json');
        $skills = $current === null ? [] : Json::decode($current, 'skills.json');
        $sources = [];

        foreach (\is_array($skills['sources'] ?? null) ? $skills['sources'] : [] as $source) {
            $generated = \is_array($source)
                && ($source['from'] ?? null) === 'dir'
                && \is_string($source['path'] ?? null)
                && str_starts_with($source['path'], Monorepo::PACKAGES_DIR . '/');

            if (!$generated) {
                $sources[] = $source;
            }
        }

        foreach ($this->monorepo->packages as $package) {
            if ($package->hasSkills) {
                $sources[] = ['from' => 'dir', 'path' => $package->path()];
            }
        }

        unset($skills['sources']);

        if ($sources !== []) {
            $skills['sources'] = $sources;
        }

        return Json::encode($skills);
    }

    private function testo(): string
    {
        $plugins = self::TESTO_PLUGINS;
        $src = '';
        $suites = '';
        $tools = glob($this->monorepo->root . '/tools/*/tests', GLOB_ONLYDIR);
        \assert($tools !== false);

        foreach ($tools as $tests) {
            $tool = basename(\dirname($tests));
            $suites .= "        new SuiteConfig(name: '{$tool}', location: [__DIR__ . '/tools/{$tool}/tests']),\n";
        }

        foreach ($this->monorepo->packages as $package) {
            $path = $package->path();
            $src .= \sprintf("        __DIR__ . '/%s/src',\n", $path);
            $suites .= is_file($this->monorepo->root . '/' . $path . '/' . $plugins)
                ? <<<PHP
                            new SuiteConfig(
                                name: '{$package->dir}',
                                location: [__DIR__ . '/{$path}/tests'],
                                plugins: require __DIR__ . '/{$path}/{$plugins}',
                            ),

                    PHP
                : "        new SuiteConfig(name: '{$package->dir}', location: [__DIR__ . '/{$path}/tests']),\n";
        }

        $src = $src === '' ? '[]' : "[\n{$src}    ]";

        return <<<PHP
            <?php

            declare(strict_types=1);

            // Generated by bin/monorepo sync, do not edit.

            use Testo\\Application\\Config\\ApplicationConfig;
            use Testo\\Application\\Config\\SuiteConfig;

            return new ApplicationConfig(
                src: {$src},
                suites: [
            {$suites}    ],
            );

            PHP;
    }

    /**
     * Plain arrays without classes: PHP CS Fixer, Rector and composer-dependency-analyser are installed globally
     * and do not load the autoloader of the monorepo, so they cannot read the manifests themselves.
     */
    private function tools(): string
    {
        $optional = '';
        $fixer = '';
        $rector = [];
        $errors = [];

        foreach ($this->monorepo->packages as $package) {
            $path = $package->path();

            if ($package->manifest->optional !== []) {
                $optional .= \sprintf(
                    "        %s => [%s],\n",
                    self::export($path . '/src'),
                    implode(', ', array_map(self::export(...), $package->manifest->optional)),
                );
            }

            foreach ($package->manifest->skip as $skip) {
                $indent = str_repeat(' ', $skip instanceof FixerSkip ? 8 : 12);
                $entry = self::comment($skip->reason, $indent);

                foreach ($skip->paths as $file) {
                    if (!file_exists($this->monorepo->root . '/' . $path . '/' . $file)) {
                        $errors[] = \sprintf(
                            '%s/%s: the skipped path %s does not exist, fix or remove the skip.',
                            $path,
                            Monorepo::MANIFEST,
                            $file,
                        );
                    }

                    $entry .= $indent . self::export($path . '/' . $file) . ",\n";
                }

                if ($skip instanceof FixerSkip) {
                    $fixer .= $entry;
                } else {
                    $rector[$skip->rule] = ($rector[$skip->rule] ?? '') . $entry;
                }
            }
        }

        if ($errors !== []) {
            throw new MonorepoException(implode("\n", $errors));
        }

        ksort($rector);
        $rules = '';

        foreach ($rector as $rule => $entries) {
            $rules .= \sprintf("        \\%s::class => [\n%s        ],\n", ltrim($rule, '\\'), $entries);
        }

        $list = static fn(string $items) => $items === '' ? '[]' : "[\n{$items}    ]";

        return <<<PHP
            <?php

            declare(strict_types=1);

            // Generated by bin/monorepo sync from optional and skip of packages/*/package.php, do not edit.
            // Paths are relative to the root.

            return [
                'optional' => {$list($optional)},
                'fixer' => {$list($fixer)},
                'rector' => {$list($rules)},
            ];

            PHP;
    }

    /**
     * A single-quoted literal as PHP CS Fixer writes it: unlike var_export(), a backslash is doubled only where
     * it would escape something.
     */
    private static function export(string $value): string
    {
        $escaped = preg_replace('/\\\(?=[\\\\\']|$)/', '\\\\\\\\', $value);
        \assert($escaped !== null);

        return "'" . str_replace("'", "\\'", $escaped) . "'";
    }

    private static function comment(string $text, string $indent): string
    {
        $prefix = $indent . '// ';
        $lines = explode("\n", wordwrap($text, 120 - \strlen($prefix)));

        return implode('', array_map(static fn(string $line) => $prefix . $line . "\n", $lines));
    }

    private function agents(): string
    {
        $agents = $this->monorepo->read('AGENTS.md') ?? '';
        $start = strpos($agents, self::CATALOG_START);
        $end = strpos($agents, self::CATALOG_END);

        if ($start === false || $end === false || $end < $start) {
            throw new MonorepoException(
                \sprintf('AGENTS.md must contain the markers %s and %s.', self::CATALOG_START, self::CATALOG_END),
            );
        }

        $before = substr(
            $agents,
            0,
            $start,
        );

        return $before
            . self::CATALOG_START . "\n\n" . $this->catalog() . "\n" . self::CATALOG_END
            . substr($agents, $end + \strlen(self::CATALOG_END));
    }

    private function catalog(): string
    {
        $lines = [];

        foreach ($this->monorepo->packages as $package) {
            $manifest = $package->manifest;
            $requires = $this->monorepo->packagesIn($manifest->require);
            $lines[] = \sprintf(
                '- `%s`: %s.%s%s',
                $package->dir,
                rtrim($manifest->description, '.'),
                $requires === [] ? '' : ' Requires: ' . implode(', ', $requires) . '.',
                $package->hasSkills ? ' Ships skills.' : '',
            );
        }

        return $lines === [] ? "No packages yet.\n" : implode("\n", $lines) . "\n";
    }

    /**
     * Composer's own order: php, php-*, ext-*, lib-*, then the rest alphabetically.
     *
     * @param array<string, string> $require
     * @return array<string, string>
     */
    private static function sortRequire(array $require): array
    {
        $rank = static fn(string $name) => match (true) {
            $name === 'php' => '0',
            str_starts_with($name, 'php-') => '1' . $name,
            str_starts_with($name, 'ext-') => '2' . $name,
            str_starts_with($name, 'lib-') => '3' . $name,
            default => '4' . $name,
        };
        uksort($require, static fn(string $a, string $b) => strcmp($rank($a), $rank($b)));

        return $require;
    }
}
