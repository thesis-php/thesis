final class Generator
{
    public const string CATALOG_START = '<!-- packages:start (generated by bin/monorepo sync, do not edit) -->';
    public const string CATALOG_END = '<!-- packages:end -->';
    public const string HEAD_START = '<!-- head:start (generated by bin/monorepo sync, do not edit) -->';
    public const string HEAD_END = '<!-- head:end -->';

    /**
     * The rules of GitHub for a topic: every keyword is one.
     */
    private const string TOPIC = '/^[a-z0-9][a-z0-9-]{0,49}$/';
    private const int MAX_TOPICS = 20;

    private string $agentsCatalog {
        get {
            $lines = [];

            foreach ($this->monorepo->packages as $package) {
                $manifest = $package->manifest;
                $requires = $this->monorepo->packagesIn($manifest->require);
                $lines[] = \sprintf(
                    '- `%s`: %s.%s%s',
                    $package->dir,
                    rtrim($manifest->description, '.'),
                    $requires === [] ? '' : ' Requires: ' . implode(', ', $requires) . '.',
                    $package->hasSkills ? ' Ships skills.' : '',
                );
            }

            return $lines === [] ? "No packages yet.\n" : implode("\n", $lines) . "\n";
        }
    }

    private string $readmeCatalog {
        get {
            if ($this->monorepo->packages === []) {
                return "No packages yet.\n";
            }

            $rows = "| Package | Release | Description |\n|---|---|---|\n";

            foreach ($this->monorepo->packages as $package) {
                $split = Repositories::ORGANIZATION . '/' . $package->dir;
                $rows .= \sprintf(
                    "| [%s](%s) | [![Release](https://img.shields.io/github/v/release/%s)](https://github.com/%s/releases) | %s |\n",
                    $package->name,
                    $package->path,
                    $split,
                    $split,
                    str_replace('|', '\|', $package->manifest->description),
                );
            }

            return $rows;
        }
    }

    /**
     * @return array<non-empty-string, string> path => content
     */
    public static function generate(Monorepo $monorepo): array
    {
        // The configs of the tools read the skips themselves: sync only fails on a stale one.
        Tools::of($monorepo);
        $generator = new self($monorepo);
        $files = [
            'composer.json' => $generator->rootComposer(),
            'skills.json' => $generator->skills(),
            'AGENTS.md' => $generator->withCatalog('AGENTS.md', $generator->agentsCatalog),
            'README.md' => $generator->withCatalog('README.md', $generator->readmeCatalog),
            'LICENSE' => $generator->license($monorepo->config->licenseSince),
            '.github/ISSUE_TEMPLATE/bug.yml' => $generator->bugForm(),
            '.github/ISSUE_TEMPLATE/feature.yml' => $generator->featureForm(),
        ];

        foreach ($monorepo->packages as $package) {
            $generator->checkReadmeLinks($package);
            $readme = $generator->packageReadme($package);

            if ($readme !== null) {
                $files[$package->path . '/README.md'] = $readme;
            }

            $files[$package->path . '/composer.json'] = Json::encode($generator->packageComposer($package));
            $files[$package->path . '/LICENSE'] = $generator->license($package->manifest->licenseSince);
            $files[$package->path . '/CONTRIBUTING.md'] = self::contributing($package);
            $files[$package->path . '/SECURITY.md'] = self::security($package);
            $files[$package->path . '/' . Monorepo::SPLIT] = $generator->splitList($package);
        }

        return $files;
    }

    /**
     * JSON is compared by meaning: composer normalize owns the formatting of composer.json,
     * so sync rewrites a file only when its content changes and never fights the formatting.
     *
     * @param array<non-empty-string, string> $files
     * @return array<non-empty-string, string> stale files: path => expected content
     */
    public static function stale(Monorepo $monorepo, array $files): array
    {
        $stale = [];

        foreach ($files as $path => $expected) {
            $actual = $monorepo->read($path);

            $same = match (true) {
                $actual === null => false,
                str_ends_with($path, '.json') => self::canonicalJson($actual, $path)
                    === self::canonicalJson($expected, $path),
                default => $actual === $expected,
            };

            if (!$same) {
                $stale[$path] = $expected;
            }
        }

        return $stale;
    }

    private function __construct(
        private readonly Monorepo $monorepo,
    ) {}

    private static function canonicalJson(string $content, string $path): mixed
    {
        return Json::canonical(Json::decode($content, $path));
    }

    /**
     * @return array<non-empty-string, mixed>
     */
    private function packageComposer(Package $package): array
    {
        $manifest = $package->manifest;
        $config = $this->monorepo->config;

        if (isset($manifest->extra['branch-alias'])) {
            throw new MonorepoException(\sprintf(
                '%s/%s: extra.branch-alias is generated from the version, remove it.',
                $package->path,
                Monorepo::MANIFEST,
            ));
        }

        $composer = [
            'name' => $package->name,
            'description' => $manifest->description,
            'keywords' => self::keywords($manifest->keywords, $package->path . '/' . Monorepo::MANIFEST),
            'license' => 'MIT',
            'type' => $manifest->type,
            'authors' => $config->authors,
            'support' => self::support($package),
            'require' => self::sortRequire([
                'php' => $config->php,
                ...$this->versioned($package, $manifest->require),
            ]),
            'require-dev' => self::sortRequire($this->versioned($package, $manifest->requireDev)),
            'conflict' => self::sortRequire($manifest->conflict),
            'suggest' => self::sortRequire($manifest->suggest),
            'autoload' => array_filter([
                'psr-4' => [$package->namespace => 'src/'],
                'files' => $package->files,
            ]),
            'autoload-dev' => array_filter([
                'psr-4' => $package->hasTests ? [$package->namespace => 'tests/'] : [],
                'files' => $package->devFiles,
            ]),
            'extra' => [
                ...$manifest->extra,
                'branch-alias' => [Series::branch() => Series::of($package)->alias],
            ],
        ];

        return array_filter($composer, static fn(mixed $value) => $value !== []);
    }

    /**
     * A monorepo package is required by the range of its series ('*' in the manifest), or by a constraint
     * of the manifest that raises the lower bound within that range.
     *
     * @param array<non-empty-string, non-empty-string> $require
     * @return array<non-empty-string, non-empty-string>
     */
    private function versioned(Package $package, array $require): array
    {
        $errors = [];

        foreach ($require as $name => $constraint) {
            $dependency = $this->monorepo->package($name);

            if ($dependency === null) {
                continue;
            }

            $series = Series::of($dependency);

            if ($constraint === '*') {
                $require[$name] = $series->range;
            } elseif (!$series->allows($constraint)) {
                $errors[] = \sprintf(
                    "%s/%s: %s is required as %s, outside %s of its series %s: require it as '*' or within %5\$s.",
                    $package->path,
                    Monorepo::MANIFEST,
                    $name,
                    $constraint,
                    $series->range,
                    $series->toString(),
                );
            }
        }

        if ($errors !== []) {
            throw new MonorepoException(implode("\n", $errors));
        }

        return $require;
    }

    private function rootComposer(): string
    {
        $config = $this->monorepo->config;
        $requirements = Requirements::resolve($this->monorepo);
        $replace = [];
        $psr4 = [];
        $files = [];
        $psr4Dev = [];
        $filesDev = [];

        foreach ($this->monorepo->packages as $package) {
            $path = $package->path;
            // The root is dev-main, which no ^0.Y of an external dependency on a package would accept.
            $replace[$package->name] = Series::of($package)->alias;
            $psr4[$package->namespace][] = $path . '/src/';

            if ($package->hasTests) {
                $psr4Dev[$package->namespace][] = $path . '/tests/';
            }

            $prefix = static fn(string $file) => $path . '/' . $file;
            $files = [...$files, ...array_map($prefix, $package->files)];
            $filesDev = [...$filesDev, ...array_map($prefix, $package->devFiles)];
        }

        $composer = [
            'name' => Monorepo::VENDOR . '/monorepo',
            'description' => $config->description,
            'keywords' => self::keywords($config->keywords, Monorepo::CONFIG),
            'license' => 'MIT',
            'type' => 'project',
            'authors' => $config->authors,
            'require' => self::sortRequire($requirements->require),
            'require-dev' => self::sortRequire($requirements->requireDev),
            'replace' => self::sortRequire($replace),
            'autoload' => array_filter(['psr-4' => self::psr4($psr4), 'files' => $files]),
            'autoload-dev' => array_filter([
                'psr-4' => [...$config->autoloadDev, ...self::psr4($psr4Dev)],
                'files' => $filesDev,
            ]),
            'config' => array_filter(['allow-plugins' => $config->allowPlugins]),
        ];

        return Json::encode(array_filter($composer, static fn(mixed $value) => $value !== []));
    }

    /**
     * Thesis\ is the prefix of every package with a root entry, so a prefix may have several directories.
     *
     * @param array<non-empty-string, non-empty-list<non-empty-string>> $directories
     * @return array<non-empty-string, non-empty-string|non-empty-list<non-empty-string>>
     */
    private static function psr4(array $directories): array
    {
        return array_map(
            static fn(array $paths) => \count($paths) === 1 ? $paths[0] : $paths,
            $directories,
        );
    }

    /**
     * What the split repository has of the package, read by the split from the commit it splits
     * (Monorepo::SPLIT). An allowlist: a new file of the monorepo stays out of the split, and so out of
     * every install, without anyone remembering to exclude it.
     */
    private function splitList(Package $package): string
    {
        $errors = [];

        foreach ($package->manifest->dist as $path) {
            $directory = strstr($path, '/', before_needle: true);
            $exists = file_exists($this->monorepo->root . '/' . $package->path . '/' . $path);
            $problem = match (true) {
                $directory !== false => "is not a top-level entry of the package, name {$directory} instead",
                !$exists => 'does not exist, fix or remove it',
                default => null,
            };

            if ($problem !== null) {
                $errors[] = \sprintf(
                    '%s/%s: the dist path %s %s.',
                    $package->path,
                    Monorepo::MANIFEST,
                    $path,
                    $problem,
                );
            }
        }

        if ($errors !== []) {
            throw new MonorepoException(implode("\n", $errors));
        }

        $listed = [
            'src',
            'composer.json',
            'LICENSE',
            'README.md',
            'CHANGELOG.md',
            'CONTRIBUTING.md',
            'SECURITY.md',
            ...$package->manifest->dist,
        ];

        if ($package->hasSkills) {
            $listed[] = 'skills';
        }

        sort($listed);

        return "# Generated by bin/monorepo sync, do not edit.\n"
            . "# The split repository has only these entries of the package.\n"
            . implode("\n", array_unique($listed)) . "\n";
    }

    /**
     * The split repository and Packagist show the package alone, so a link out of it (../async, or /AGENTS.md,
     * which GitHub resolves from the root of the repository) works only in the monorepo.
     */
    private function checkReadmeLinks(Package $package): void
    {
        $path = $package->path . '/README.md';
        $readme = $this->monorepo->read($path);

        if ($readme === null) {
            return;
        }

        // A link in code is an example, not a link.
        $text = preg_replace(['/^ *(```|~~~).*?^ *\1/ms', '/`[^`\n]*`/'], '', $readme);
        \assert($text !== null);
        preg_match_all(
            '/\]\(\s*<?([^\s>)]+)|^ {0,3}\[[^\]]+\]:\s*<?([^\s>]+)|\b(?:href|src)\s*=\s*["\']([^"\']+)/m',
            $text,
            $matches,
            PREG_SET_ORDER | PREG_UNMATCHED_AS_NULL,
        );
        $errors = [];

        foreach ($matches as $match) {
            $link = $match[1] ?? $match[2] ?? $match[3] ?? '';

            if (self::isOutsideOfPackage($link)) {
                $errors[] = \sprintf(
                    '%s: %s links outside of the package, which the split repository and Packagist do not have: '
                    . 'link a package by https://github.com/%s/<name>.',
                    $path,
                    $link,
                    Repositories::ORGANIZATION,
                );
            }
        }

        if ($errors !== []) {
            throw new MonorepoException(implode("\n", $errors));
        }
    }

    /**
     * The head of README.md is generated: the title, the badges and a note that says where the package
     * is developed, since the split repository has neither the tests nor pull requests (agents/repositories.md).
     * The badges are of what needs no service and no secret and says something already for a new package:
     * the PHP of Packagist, the release of the split, the license and the level of PHPStan.
     */
    private function packageReadme(Package $package): ?string
    {
        $path = $package->path . '/README.md';
        $readme = $this->monorepo->read($path);

        if ($readme === null) {
            return null;
        }

        $monorepo = Repositories::ORGANIZATION . '/' . Repositories::MONOREPO;
        $split = Repositories::ORGANIZATION . '/' . $package->dir;
        $branch = Repositories::DEFAULT_BRANCH;
        $packagist = "https://packagist.org/packages/{$package->name}";
        $bug = self::newIssue('bug');
        $feature = self::newIssue('feature');
        $license = "https://github.com/{$split}/blob/{$branch}/LICENSE";
        $level = $this->phpstanLevel();
        $head = <<<MD
            # {$package->title}

            [![PHP](https://img.shields.io/packagist/dependency-v/{$package->name}/php)]({$packagist})
            [![Release](https://img.shields.io/github/v/release/{$split})](https://github.com/{$split}/releases)
            [![License](https://img.shields.io/packagist/l/{$package->name})]({$license})
            [![PHPStan](https://img.shields.io/badge/PHPStan-level%20{$level}-brightgreen)](https://github.com/{$monorepo}/blob/{$branch}/phpstan.neon)

            > A read-only split of [`{$package->path}`](https://github.com/{$monorepo}/tree/{$branch}/{$package->path})
            > in the monorepo [{$monorepo}](https://github.com/{$monorepo}): issues and pull requests go there.
            >
            > [Report a bug]({$bug}) · [Request a feature]({$feature}) · [Changelog](CHANGELOG.md)
            > · [Contributing](CONTRIBUTING.md)
            MD;

        return self::withHead($readme, $head);
    }

    /**
     * The split repository is read-only (agents/repositories.md), so how to contribute is the same
     * for every package: in the monorepo, with its make targets narrowed to the package.
     */
    private static function contributing(Package $package): string
    {
        $monorepo = Repositories::ORGANIZATION . '/' . Repositories::MONOREPO;
        $branch = Repositories::DEFAULT_BRANCH;
        $directory = "https://github.com/{$monorepo}/tree/{$branch}/{$package->path}";
        $bug = self::newIssue('bug');
        $feature = self::newIssue('feature');

        return <<<MD
            <!-- Generated by bin/monorepo sync, do not edit. -->

            # Contributing to {$package->name}

            `{$package->name}` is developed in the monorepo [{$monorepo}](https://github.com/{$monorepo}),
            in [`{$package->path}`]({$directory}), together with its tests and the other Thesis packages.
            This repository is a read-only split: on every push to `{$branch}` of the monorepo, CI copies into it
            what composer installs. Issues and pull requests are disabled here, and a commit made here would be lost
            on the next split.

            ## Issues

            [Report a bug]({$bug}) or [request a feature]({$feature}) in the issues of the monorepo
            and choose `{$package->name}` in it. For a bug give its version, the code that reproduces it,
            what you expected and what happened instead. A vulnerability is reported privately, see
            [SECURITY.md](SECURITY.md).

            ## Pull requests

            You need Git, Docker and Make: everything runs in containers, on the PHP version of the monorepo.

            1. Fork [{$monorepo}](https://github.com/{$monorepo}) and clone your fork.
            2. Install the dependencies: `make i`.
            3. Change the code in `{$package->path}/src/` and its tests in `{$package->path}/tests/`.
               Every change is covered by a test.
            4. Check the package while you work:
               - `make test P={$package->dir}` runs its tests and starts the services they need,
               - `make phpstan P={$package->dir}` runs static analysis,
               - `make fix P={$package->dir}` applies Rector and the code style.
            5. A change that users of the package can notice gets an entry under `## [Unreleased]`
               of `{$package->path}/CHANGELOG.md` ([Keep a Changelog](https://keepachangelog.com/en/1.1.0/)).
               Leave the version headings alone: the maintainers release a version by adding one.
            6. If you changed `{$package->path}/package.php` (dependencies, description, keywords),
               run `make sync` and commit the files it generates: CI fails on any difference.
            7. Run `make check`, everything CI runs, and open a pull request to `{$branch}` of the monorepo.

            The rules of the code and of the monorepo are in
            [`AGENTS.md`](https://github.com/{$monorepo}/blob/{$branch}/AGENTS.md) and the files it links.

            MD;
    }

