<?php

declare(strict_types=1);

namespace Thesis\Monorepo\Internal;

use Composer\Semver\VersionParser;

/**
 * The matrices of the jobs of check.yaml that run per package, derived from the manifests: no list of packages
 * is written by hand (agents/manifests.md). The workflow itself is written by hand, sync rewrites only the line
 * under each marker.
 *
 * @internal
 */
final readonly class Matrices
{
    public const string PATH = '.github/workflows/check.yaml';
    private const string MARKER = '(generated by bin/monorepo sync, do not edit)';

    /**
     * @return non-empty-string the workflow with the matrices of the manifests
     */
    public static function write(Monorepo $monorepo): string
    {
        $workflow = $monorepo->read(self::PATH) ?? throw new MonorepoException(self::PATH . ' does not exist.');
        $matrices = new self($monorepo)->matrices();
        $written = [];

        $workflow = preg_replace_callback(
            pattern: '/^( *)# (\S+) ' . preg_quote(self::MARKER, '/') . '\n[^\n]*$/m',
            callback: static function (array $match) use ($matrices, &$written) {
                [, $indent, $job] = $match;
                $matrix = $matrices[$job] ?? throw new MonorepoException(
                    \sprintf('%s: no matrix of the manifests is named %s.', self::PATH, $job),
                );
                $written[] = $job;

                return "{$indent}# {$job} " . self::MARKER . "\n{$indent}{$matrix}";
            },
            subject: $workflow,
        );
        \assert($workflow !== null && $workflow !== '');

        $missing = array_diff(array_keys($matrices), $written);

        if ($missing !== []) {
            throw new MonorepoException(\sprintf(
                '%s: the matrix of %s needs a line "# <job> %s" above it.',
                self::PATH,
                implode(', ', $missing),
                self::MARKER,
            ));
        }

        return $workflow;
    }

    private function __construct(
        private Monorepo $monorepo,
    ) {}

    /**
     * @return array<non-empty-string, non-empty-string> job => the line of its matrix
     */
    private function matrices(): array
    {
        $tested = array_filter($this->monorepo->packages, static fn(Package $package) => $package->hasTests);
        $mutated = array_filter($tested, static fn(Package $package) => $package->isMutationTested);
        $alone = [];
        $bits32 = [];
        $monorepoPhp = self::minor($this->monorepo->config->php);

        foreach ($this->monorepo->packages as $package) {
            $php = self::minor($package->manifest->require['php'] ?? $this->monorepo->config->php);

            foreach (self::minorsBetween($php, $monorepoPhp) as $version) {
                $alone[] = "{package: {$package->dir}, php: '{$version}'}";
            }

            if ($package->manifest->bit32Testing) {
                foreach (array_unique([self::version($php), self::version($monorepoPhp)]) as $version) {
                    $bits32[] = "{package: {$package->dir}, php: '{$version}'}";
                }
            }
        }

        return [
            'test-alone' => 'include: [' . implode(', ', $alone) . ']',
            'test-32-bit' => 'include: [' . implode(', ', $bits32) . ']',
            'infect' => 'package: ' . self::names($mutated),
            'coverage' => 'package: ' . self::names($tested),
        ];
    }

    /**
     * @param array<Package> $packages
     * @return non-empty-string
     */
    private static function names(array $packages): string
    {
        return '[' . implode(', ', array_map(static fn(Package $package) => $package->dir, $packages)) . ']';
    }

    /**
     * @return array{int, int} the major and the minor of the lower bound: [8, 2] of '^8.2.2'
     */
    private static function minor(string $constraint): array
    {
        $lowest = new VersionParser()->parseConstraints($constraint)->getLowerBound()->getVersion();

        if (preg_match('/^(\d+)\.(\d+)\./', $lowest, $match) !== 1) {
            throw new MonorepoException(\sprintf('The PHP constraint %s has no lower bound.', $constraint));
        }

        return [(int) $match[1], (int) $match[2]];
    }

    /**
     * The PHP versions on which a package runs and the monorepo does not: from its lowest to the one before
     * that of the monorepo. Only within a major: the last minor of a major is not known from the numbers.
     *
     * @param array{int, int} $from
     * @param array{int, int} $to
     * @return list<non-empty-string>
     */
    private static function minorsBetween(array $from, array $to): array
    {
        [$major, $fromMinor] = $from;
        [$toMajor, $toMinor] = $to;

        if ($major !== $toMajor) {
            throw new MonorepoException(\sprintf(
                'The minors of PHP between %d.%d and %d.%d are not known.',
                $major,
                $fromMinor,
                $toMajor,
                $toMinor,
            ));
        }

        return array_map(
            static fn(int $minor) => "{$major}.{$minor}",
            $fromMinor < $toMinor ? range($fromMinor, $toMinor - 1) : [],
        );
    }

    /**
     * @param array{int, int} $version
     * @return non-empty-string
     */
    private static function version(array $version): string
    {
        return "{$version[0]}.{$version[1]}";
    }
}
