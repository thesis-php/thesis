<?php

declare(strict_types=1);

namespace Thesis\Monorepo\Tests;

use Testo\Assert;
use Testo\Expect;
use Testo\Test;
use Thesis\Monorepo\Internal\Matrices;
use Thesis\Monorepo\Internal\MonorepoException;

#[Test]
final readonly class MatricesTest
{
    public static function derivesMatricesFromManifests(): void
    {
        $fixture = new Fixture()
            ->file('packages/bytes/tests/BytesTest.php', "<?php\n")
            ->file('packages/clock/tests/ClockTest.php', "<?php\n")
            ->file('packages/wire/tests/WireTest.php', "<?php\n")
            ->package('bytes')
            ->package('clock', "require: ['php' => '^8.3.1'], bit32Testing: true")
            ->package('stan')
            ->package('wire', 'mutationTesting: false')
        ;

        Assert::same(Matrices::write($fixture->load()), <<<'YAML'
            jobs:
              test-alone:
                # test-alone (generated by bin/monorepo sync, do not edit)
                include:
                  - {package: clock, php: '8.3'}
                  - {package: clock, php: '8.4'}
              test-32-bit:
                # test-32-bit (generated by bin/monorepo sync, do not edit)
                include:
                  - {package: clock, php: '8.3'}
                  - {package: clock, php: '8.5'}
              infect:
                # infect (generated by bin/monorepo sync, do not edit)
                package:
                  - bytes
                  - clock
              coverage:
                # coverage (generated by bin/monorepo sync, do not edit)
                package:
                  - bytes
                  - clock
                  - wire

            YAML);
    }

    public static function replacesMatrixOfEarlierSyncAndKeepsRestOfWorkflow(): void
    {
        $workflow = <<<'YAML'
            jobs:
              coverage:
                strategy:
                  matrix:
                    # coverage (generated by bin/monorepo sync, do not edit)
                    package:
                      - bytes
                      - removed
                steps:
                  - run: make coverage

            YAML;
        $fixture = new Fixture()
            ->file('packages/bytes/tests/BytesTest.php', "<?php\n")
            ->package('bytes')
            ->file(Matrices::PATH, $workflow . Fixture::workflow())
        ;

        Assert::string(Matrices::write($fixture->load()))->contains(<<<'YAML'
            jobs:
              coverage:
                strategy:
                  matrix:
                    # coverage (generated by bin/monorepo sync, do not edit)
                    package:
                      - bytes
                steps:
                  - run: make coverage

            YAML);
    }

    public static function testsOn32BitOnceWhenPackageHasPhpOfMonorepo(): void
    {
        $fixture = new Fixture()->package('bytes', 'bit32Testing: true');

        Assert
            ::string(Matrices::write($fixture->load()))
            ->contains("    include:\n      - {package: bytes, php: '8.5'}\n")
            ->contains("    include: []\n")
        ;
    }

    public static function failsOnUnknownMatrix(): void
    {
        $fixture = new Fixture()->file(
            Matrices::PATH,
            Fixture::workflow() . "  lint:\n    # lint (generated by bin/monorepo sync, do not edit)\n    x: []\n",
        );

        Expect::exception(MonorepoException::class)->withMessage(
            '.github/workflows/check.yaml: no matrix of the manifests is named lint.',
        );

        Matrices::write($fixture->load());
    }

    public static function failsOnMissingMarker(): void
    {
        $fixture = new Fixture()->file(Matrices::PATH, "jobs:\n  infect:\n    package: [bytes]\n");

        Expect::exception(MonorepoException::class)->withMessage(
            '.github/workflows/check.yaml: the matrix of test-alone, test-32-bit, infect, coverage needs a line'
            . ' "# <job> (generated by bin/monorepo sync, do not edit)" above it.',
        );

        Matrices::write($fixture->load());
    }

    public static function failsOnPhpOfAnotherMajor(): void
    {
        $fixture = new Fixture()->package('bytes', "require: ['php' => '^7.4']");

        Expect::exception(MonorepoException::class)->withMessage('The minors of PHP between 7.4 and 8.5 are not known.');

        Matrices::write($fixture->load());
    }
}
