<?php

declare(strict_types=1);

namespace Thesis\Monorepo\Tests;

use Thesis\Monorepo\Internal\Generator;
use Thesis\Monorepo\Internal\Matrices;
use Thesis\Monorepo\Internal\Monorepo;

final readonly class Fixture
{
    public string $root;

    public function __construct()
    {
        $this->root = sys_get_temp_dir() . '/monorepo-' . bin2hex(random_bytes(8));
        $this->file('monorepo.php', <<<'PHP'
            <?php

            return new Thesis\Monorepo\Config(
                php: '^8.5',
                description: 'Fixture.',
                copyrightHolder: 'Fixture',
                licenseSince: 2026,
            );
            PHP);
        $this->file('skills.json', "{}\n");
        $this->file('phpstan.neon', "parameters:\n    level: max\n");
        $this->file('AGENTS.md', "# Fixture\n\n" . Generator::CATALOG_START . "\n" . Generator::CATALOG_END . "\n");
        $this->file('README.md', "# Fixture\n\n" . Generator::CATALOG_START . "\n" . Generator::CATALOG_END . "\n");
        $this->file(Matrices::CHECK, self::workflow());
        $this->file(Matrices::INFECTION, self::workflow(['infect']));
    }

    /**
     * @param list<string> $jobs
     */
    public static function workflow(array $jobs = ['test-alone', 'test-32-bit', 'coverage']): string
    {
        $jobs = array_map(
            static fn(string $job) => "  {$job}:\n    # {$job} (generated by bin/monorepo sync, do not edit)\n    x: []\n",
            $jobs,
        );

        return "jobs:\n" . implode('', $jobs);
    }

    /**
     * @param string $arguments named arguments of Manifest after the description, the license year and the version,
     *     as PHP code
     */
    public function package(
        string $dir,
        string $arguments = '',
        int $licenseSince = 2026,
        string $version = '0.1',
    ): self {
        $this->file("packages/{$dir}/package.php", <<<PHP
            <?php

            return new Thesis\\Monorepo\\Manifest(
                description: 'Package {$dir}.',
                licenseSince: {$licenseSince},
                version: '{$version}',
                {$arguments}
            );
            PHP);

        return $this;
    }

    public function file(string $path, string $content): self
    {
        $file = $this->root . '/' . $path;

        if (!is_dir(\dirname($file))) {
            mkdir(\dirname($file), recursive: true);
        }

        file_put_contents($file, $content);

        return $this;
    }

    public function load(): Monorepo
    {
        return Monorepo::load($this->root);
    }

    public static function remove(string $dir): void
    {
        if (!is_dir($dir)) {
            return;
        }

        /** @var \SplFileInfo $file */
        foreach (new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($dir, \FilesystemIterator::SKIP_DOTS),
            \RecursiveIteratorIterator::CHILD_FIRST,
        ) as $file) {
            $file->isDir() && !$file->isLink() ? rmdir($file->getPathname()) : unlink($file->getPathname());
        }

        rmdir($dir);
    }

    public function __destruct()
    {
        self::remove($this->root);
    }
}
